export function generateInitialPayrollRuns(): PayrollRun[] {
  const employees = initialEmployees;
  const payslips = employees.map(emp => {
    const gross = emp.basicSalary + emp.housingAllowance + emp.transportAllowance + emp.foodAllowance + emp.otherAllowances;
    const gosiEmp = Math.round((emp.basicSalary + emp.housingAllowance) * (emp.gosiDeductionPct / 100));
    const tax = Math.round(gross * (emp.taxDeductionPct / 100));
    const totalDeductions = gosiEmp + tax;
    const net = gross - totalDeductions;
    const gosiComp = Math.round((emp.basicSalary + emp.housingAllowance) * (emp.gosiCompanyContributionPct / 100));

    return {
      id: `PS-2026-03-${emp.employeeCode}`,
      employeeId: emp.id,
      employeeCode: emp.employeeCode,
      employeeName: `${emp.firstNameAr} ${emp.lastNameAr}`,
      jobTitle: emp.jobTitle,
      department: emp.department,
      costCenterId: emp.costCenterId,
      bankName: emp.bankName,
      iban: emp.ibanOrAccountNumber,
      month: 3,
      year: 2026,
      basicSalary: emp.basicSalary,
      housingAllowance: emp.housingAllowance,
      transportAllowance: emp.transportAllowance,
      foodAllowance: emp.foodAllowance,
      overtimeAmount: 0,
      bonuses: 0,
      grossSalary: gross,
      gosiEmployeeDeduction: gosiEmp,
      incomeTaxDeduction: tax,
      advancesAndLoansDeduction: 0,
      absenceAndPenaltiesDeduction: 0,
      totalDeductions,
      netSalary: net,
      gosiCompanyContribution: gosiComp,
      status: 'PAID' as const,
      paymentDate: '2026-03-31',
    };
  });

  const totalGross = payslips.reduce((s, p) => s + p.grossSalary, 0);
  const totalDed = payslips.reduce((s, p) => s + p.totalDeductions, 0);
  const totalNet = payslips.reduce((s, p) => s + p.netSalary, 0);
  const totalComp = payslips.reduce((s, p) => s + p.gosiCompanyContribution, 0);

  return [
    {
      id: 'PAY-2026-03',
      payrollNumber: 'PAY-2026-03',
      month: 3,
      year: 2026,
      periodName: 'مسير رواتب شهر مارس 2026',
      dateProcessed: '2026-03-30',
      totalEmployees: payslips.length,
      totalGrossAmount: totalGross,
      totalDeductionsAmount: totalDed,
      totalNetAmount: totalNet,
      totalCompanyContributions: totalComp,
      currency: 'YER',
      status: 'POSTED_TO_GL',
      payslips,
      journalEntryId: 'JV-2026-03-PAY',
      postedBy: 'أحمد السعيد (CFO)',
      postedAt: '2026-03-31 10:30',
    },
  ];
}
