export function parseVendorsCsv(csvText: string): Vendor[] {
  const lines = csvText.trim().split('\n');
  const vendors: Vendor[] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line || line.startsWith('تقرير') || line.startsWith('مجموعة') || line.startsWith('م,') || line.startsWith(',الإجمالي')) {
      continue;
    }

    const parts = line.split(',');
    if (parts.length < 2) continue;

    const seq = parts[0]?.trim();
    const name = parts[1]?.trim();
    if (!name || name === 'الإجمالي العام') continue;

    const rateStr = parts[2]?.trim() || '0';
    const paidStr = parts[3]?.trim() || '0';
    const opsStr = parts[4]?.trim() || '0';
    const balStr = parts[5]?.trim() || '0';

    const paymentRate = parseFloat(rateStr) || 0;
    const totalPaid = parseFloat(paidStr) || 0;
    const totalOperations = parseFloat(opsStr) || 0;
    const currentBalance = parseFloat(balStr) || 0;

    const code = `V-${String(vendors.length + 1).padStart(4, '0')}`;
    const id = `VEND-${String(vendors.length + 1).padStart(4, '0')}`;

    vendors.push({
      id,
      code,
      nameAr: name,
      nameEn: `Vendor ${code}`,
      phone: '+967 77' + Math.floor(1000000 + Math.random() * 8999999),
      email: `vendor_${code.toLowerCase()}@partners.ye`,
      city: 'صنعاء / عمران / صعدة',
      currency: 'YER',
      currentBalance,
      totalPaid,
      totalOperations: totalOperations || (totalPaid + currentBalance),
      paymentRate,
      paymentTermsDays: 30,
      status: currentBalance > 0 ? 'ACTIVE' : 'ACTIVE',
      notes: `المجموعة التجارية الزراعية - سجل رقم (${seq})`,
    });
  }

  return vendors;
}

